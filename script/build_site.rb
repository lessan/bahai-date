#!/usr/bin/env ruby
# Builds the GitHub Pages site into _site/ from docs/:
#
#   bundle exec ruby script/build_site.rb
#   python3 script/serve_site.py            # then open http://127.0.0.1:8000/
#
# Markdown pages are rendered into site/layout.html, and also published as
# Markdown at the same path (rules.md beside rules.html) for AI agents.
# Everything else in docs/ (the dataset, llms.txt, scripts, styles) is copied
# as it is. Links between Markdown files (foo.md, data/README.md) become links
# between pages, so the same files read correctly on GitHub and on the site.
# llms-full.txt bundles the main pages, and sitemap.xml lists them.

require "cgi"
require "fileutils"
require "json"
require "kramdown"
require "kramdown-parser-gfm"

module Site
  ROOT = File.expand_path("..", __dir__)
  DOCS = File.join(ROOT, "docs")
  URL = "https://lessan.github.io/bahai-date/"
  LAYOUT_FILE = File.join(DOCS, "site", "layout.html")

  # Pages in navigation order, as [Markdown source, label].
  NAV = [
    ["rules.md", "Rules"],
    ["years.md", "Years"],
    ["history.md", "History"],
    ["data/README.md", "Data"],
    ["sources.md", "Sources"]
  ].freeze

  # The pages bundled into llms-full.txt, in order.
  FULL = %w[index.md rules.md history.md data/README.md sources.md].freeze

  def self.page_path(md)
    md.sub(/README\.md\z/, "index.html").sub(/\.md\z/, ".html")
  end

  def self.title(markdown)
    markdown[/^# (.+)$/, 1] || "Bahá’í dates"
  end

  # The first paragraph after the title, as plain text, for <meta name="description">.
  def self.description(markdown)
    para = markdown.split(/\n\s*\n/).find { |block| !block.start_with?("#", "<", "|", "-", "```") && block.strip.length > 40 }
    text = para.to_s.gsub(/\[([^\]]*)\]\([^)]*\)/, '\1').gsub(/[*`_]/, "").gsub(/\s+/, " ").strip
    (text.length > 300) ? "#{text[0, 297].sub(/\s+\S*\z/, "")}…" : text
  end

  # Relative path from a page back to the site root, for links in the layout.
  def self.root_for(path)
    "../" * path.count("/")
  end

  def self.nav(current, root)
    NAV.map do |md, label|
      attrs = (md == current) ? ' aria-current="page"' : ""
      %(<a href="#{root}#{page_path(md)}"#{attrs}>#{label}</a>)
    end.join("\n    ")
  end

  # Structured data for the dataset page (schema.org Dataset).
  def self.dataset_json_ld
    data = {
      "@context": "https://schema.org",
      "@type": "Dataset",
      name: "Bahá’í (Badí‘) calendar dates, 1 to 1157 B.E.",
      description: "Naw-Rúz, the months, Ayyám-i-Há, the Fast and the Holy Days for every year of the Bahá’í (Badí‘) calendar from 1844 to 3001, with a confidence label for each year, generated by the bahai_date Ruby gem and checked against the official dates for 172–221 B.E.",
      url: "#{URL}data/",
      license: "https://unlicense.org/",
      isAccessibleForFree: true,
      creator: {"@type": "Person", name: "Lessan Vaezi"},
      temporalCoverage: "1844-03-21/3001-03-20",
      distribution: [
        {"@type": "DataDownload", encodingFormat: "application/json", contentUrl: "#{URL}data/years.json"},
        {"@type": "DataDownload", encodingFormat: "text/csv", contentUrl: "#{URL}data/years.csv"},
        {"@type": "DataDownload", encodingFormat: "text/csv", contentUrl: "#{URL}data/holy-days.csv"},
        {"@type": "DataDownload", encodingFormat: "text/csv", contentUrl: "#{URL}data/months.csv"}
      ]
    }
    %(<script type="application/ld+json">#{JSON.generate(data)}</script>)
  end

  def self.render(md)
    markdown = File.read(File.join(DOCS, md))
    html = Kramdown::Document.new(markdown, input: "GFM", hard_wrap: false, auto_ids: true).to_html
    html = html.gsub(/href="(?!https?:|#|mailto:)([^"]*?)(README)?\.md(#[^"]*)?"/) do
      target, readme, anchor = $1, $2, $3
      "href=\"#{target}#{"index" if readme}.html#{anchor}\""
    end
    html = html.gsub("<table>", %(<div class="table-wrap"><table>)).gsub("</table>", "</table></div>")
    # Plain ASCII anchors (declaration-of-the-bab-1844, not ...-báb-...), so links
    # to sections are easy to type and to quote.
    html = html.gsub(/ id="([^"]+)"/) { %( id="#{anchor($1)}") }
    html = html.gsub(/href="([^"#]*)#([^"]+)"/) { %(href="#{$1}##{anchor($2)}") }
    path = page_path(md)
    root = root_for(path)
    canonical = URL + path.sub(/(\A|\/)index\.html\z/, '\1')
    head = %(<link rel="canonical" href="#{canonical}">\n<link rel="alternate" type="text/markdown" href="#{root}#{md}">)
    head += "\n#{dataset_json_ld}" if md == "data/README.md"
    File.read(LAYOUT_FILE)
      .gsub("{{title}}", CGI.escapeHTML(title(markdown)))
      .gsub("{{description}}", CGI.escapeHTML(description(markdown)))
      .gsub("{{head}}", head)
      .gsub("{{nav}}", nav(md, root))
      .gsub("{{root}}", root)
      .gsub("{{content}}", html)
  end

  def self.anchor(id)
    CGI.unescape(id).unicode_normalize(:nfd).gsub(/\p{Mn}/, "").downcase.gsub(/[^a-z0-9_-]/, "")
  end

  def self.llms_full
    intro = "# Bahá’í dates: the full documentation\n\n" \
      "All pages of #{URL} in one file, for AI systems. Each page is also at #{URL}<name>.md.\n" \
      "Dates: every Gregorian date is the day on which the Bahá’í day ends (it begins at sunset the evening before).\n"
    pages = FULL.map do |md|
      "\n\n---\n\n<!-- #{URL}#{md} -->\n\n" + File.read(File.join(DOCS, md))
    end
    intro + pages.join
  end

  def self.sitemap(out)
    urls = Dir.glob("**/*.html", base: out).sort.map { |p| URL + p.sub(/(\A|\/)index\.html\z/, '\1') }
    urls += %w[llms.txt llms-full.txt data/years.json data/facts.json data/events.json data/test-vectors.json].map { |p| URL + p }
    %(<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n) +
      urls.map { |u| "  <url><loc>#{u}</loc></url>\n" }.join + "</urlset>\n"
  end

  def self.build(out = File.join(ROOT, "_site"))
    FileUtils.rm_rf(out)
    FileUtils.mkdir_p(out)
    Dir.glob("**/*", base: DOCS).sort.each do |rel|
      src = File.join(DOCS, rel)
      next if File.directory?(src) || rel == "site/layout.html"

      dest = File.join(out, rel)
      FileUtils.mkdir_p(File.dirname(dest))
      FileUtils.cp(src, dest)
      File.write(File.join(out, page_path(rel)), render(rel)) if rel.end_with?(".md")
    end
    File.write(File.join(out, "llms-full.txt"), llms_full)
    File.write(File.join(out, "sitemap.xml"), sitemap(out))
    File.write(File.join(out, ".nojekyll"), "")
    out
  end
end

Site.build if $PROGRAM_NAME == __FILE__
